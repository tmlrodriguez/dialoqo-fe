const ENGLISH_TO_SPANISH = Object.fromEntries(
    Object.entries(TRANSLATIONS).map(([spanish, english]) => [
        english,
        spanish,
    ])
);


/**
 * usePageTranslation
 *
 * Description:
 * - Proporcionar traducción simple entre español e inglés para textos visibles
 *   de las páginas de Dialoqo.
 *
 * Notes:
 * - Español es el idioma fuente del catálogo.
 * - Cuando el idioma activo es inglés, busca el texto español en TRANSLATIONS.
 * - Cuando el idioma activo es español, también puede convertir textos ingleses
 *   previamente utilizados en los componentes.
 * - Si un texto no está registrado, se devuelve sin modificaciones.
 */
export function usePageTranslation() {
    const { language } = useLanguage();

    const t = useCallback(
        (text) => {
            if (
                text === null ||
                text === undefined
            ) {
                return text;
            }

            if (
                typeof text !== "string"
            ) {
                return text;
            }

            if (language === "en") {
                return (
                    TRANSLATIONS[text] ||
                    text
                );
            }

            if (
                Object.prototype.hasOwnProperty.call(
                    TRANSLATIONS,
                    text
                )
            ) {
                return text;
            }

            return (
                ENGLISH_TO_SPANISH[text] ||
                text
            );
        },
        [language]
    );

    return {
        language,
        t,
    };
}